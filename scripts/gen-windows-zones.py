"""Regenerates crates/core/src/tz_table.rs from CLDR's windowsZones.xml.

Usage: scripts/gen-windows-zones.py path/to/windowsZones.xml

Get the file from
https://github.com/unicode-org/cldr/blob/main/common/supplemental/windowsZones.xml
"""
import sys
import xml.etree.ElementTree as ET

root = ET.parse(sys.argv[1]).getroot()
version = root.find(".//windowsZones/mapTimezones")
other_version = version.get("otherVersion", "?")
type_version = version.get("typeVersion", "?")
primary = {}
to_windows = {}
for z in root.iter("mapZone"):
    win, terr, ianas = z.get("other"), z.get("territory"), z.get("type").split()
    if terr == "001":
        primary[win] = ianas[0]
    for i in ianas:
        to_windows.setdefault(i, win)
# Every primary zone maps back to its own Windows name.
for win, iana in primary.items():
    to_windows[iana] = win

out = [
    "// SPDX-License-Identifier: MIT OR Apache-2.0",
    "// Generated by scripts/gen-windows-zones.py from CLDR windowsZones.xml",
    f"// (Windows zones {other_version}, tz {type_version}). Do not edit.",
    "",
    "/// Windows zone name to its primary IANA zone (CLDR territory 001), sorted by Windows name.",
    "pub(crate) static WINDOWS_TO_IANA: &[(&str, &str)] = &[",
]
for win in sorted(primary):
    out.append(f'    ("{win}", "{primary[win]}"),')
out += [
    "];",
    "",
    "/// IANA zone to Windows zone name, sorted by IANA name.",
    "pub(crate) static IANA_TO_WINDOWS: &[(&str, &str)] = &[",
]
for iana in sorted(to_windows):
    out.append(f'    ("{iana}", "{to_windows[iana]}"),')
out += ["];", ""]
open("crates/core/src/tz_table.rs", "w").write("\n".join(out))
print(f"{len(primary)} Windows zones, {len(to_windows)} IANA zones")
